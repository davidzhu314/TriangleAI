/**
 * fixture-y: the smallest valid case (PLAN.md). One aorta edge splitting into two branches, one
 * entry, two targets, one heavy risk zone. A test fixture, not anatomy. Millimetres, RAS.
 *
 * Built from the contract types so the files cannot drift from them. Regenerate with `pnpm fixtures`.
 */
import { CASE_SCHEMA_ID, type BundledCaseIndex, type CaseJson, type CenterlineEdge, type CenterlinesJson } from '../../client/src/contracts/case';
import type { Vec3 } from '../../client/src/contracts/events';
import { writeGlb, type GlbMesh } from '../lib/glb';
import { roundTo, stableStringify } from '../lib/stable-json';
import { appendTube, type TubeGeometry } from '../lib/tube';

const DECIMALS = 4;
const SQRT1_2 = 0.7071067811865476; // sin 45° = cos 45°
const COS30 = 0.8660254037844386;

/** A straight edge sampled every 1 mm from `start` along unit `dir` for `lengthMm`. */
function straightEdge(
  id: string, from: string, to: string, vessel: string,
  start: Vec3, dir: Vec3, lengthMm: number, radiusMm: number,
): CenterlineEdge {
  const points: Vec3[] = [];
  for (let i = 0; i <= lengthMm; i++) {
    points.push([
      roundTo(start[0] + dir[0] * i, DECIMALS),
      roundTo(start[1] + dir[1] * i, DECIMALS),
      roundTo(start[2] + dir[2] * i, DECIMALS),
    ]);
  }
  return { id, from, to, vessel, points, radii_mm: points.map(() => radiusMm) };
}

export function buildFixtureY() {
  const split: Vec3 = [0, 0, 100];
  const aorta = straightEdge('e_aorta', 'n_entry', 'n_split', 'aorta', [0, 0, 0], [0, 0, 1], 100, 12);
  // RAS: −x is the patient's left. Left branch leaves at 45°, right at 30°, from vertical.
  const left = straightEdge('e_left', 'n_split', 'n_left', 'branch_l', split, [-SQRT1_2, 0, SQRT1_2], 50, 3.5);
  const right = straightEdge('e_right', 'n_split', 'n_right', 'branch_r', split, [0.5, 0, COS30], 60, 4);
  const edges = [aorta, left, right];

  const centerlines: CenterlinesJson = {
    nodes: [
      { id: 'n_entry', pos: aorta.points[0]!, kind: 'entry' },
      { id: 'n_split', pos: split, kind: 'branch' },
      { id: 'n_left', pos: left.points.at(-1)!, kind: 'target' },
      { id: 'n_right', pos: right.points.at(-1)!, kind: 'target' },
    ],
    edges,
  };

  const caseJson: CaseJson = {
    schema: CASE_SCHEMA_ID,
    id: 'fixture-y',
    title: 'Test fixture: Y branch',
    units: 'mm',
    axes: 'RAS',
    source: { kind: 'parametric', dataset: 'fixture-y (tools/fixture-y)', license: 'Generated by ThreadSim tools; no third-party data' },
    physics: { available: false },
    scenario: 'Test fixture: one vessel splitting into two branches. Not anatomy.',
    difficulty: 'beginner',
    fluoro_budget_s: 60,
    vessels: [
      { id: 'aorta', name: 'Aorta', kind: 'artery' },
      { id: 'branch_l', name: 'Left branch', kind: 'artery' },
      { id: 'branch_r', name: 'Right branch', kind: 'artery' },
    ],
    entries: [{ id: 'fem_r', name: 'Right femoral', node: 'n_entry' }],
    targets: [
      { id: 'left_branch', name: 'Left branch', node: 'n_left' },
      { id: 'right_branch', name: 'Right branch', node: 'n_right' },
    ],
    riskZones: [{ id: 'plaque_r', kind: 'plaque', tier: 'heavy', edge: 'e_right', from_mm: 10, to_mm: 35 }],
  };

  const meshes: GlbMesh[] = caseJson.vessels.map((v) => {
    const g: TubeGeometry = { positions: [], normals: [], indices: [] };
    for (const e of edges.filter((x) => x.vessel === v.id)) appendTube(g, e.points, e.radii_mm);
    return {
      name: v.id,
      positions: Float32Array.from(g.positions),
      normals: Float32Array.from(g.normals),
      indices: Uint32Array.from(g.indices),
    };
  });

  const index: BundledCaseIndex = { cases: [{ id: 'fixture-y', path: 'fixture-y/' }] };

  return {
    files: {
      'fixture-y/case.json': stableStringify(caseJson),
      'fixture-y/centerlines.json': stableStringify(centerlines),
      'fixture-y/vessels.glb': writeGlb(meshes, { units: 'mm', axes: 'RAS' }),
      'index.json': stableStringify(index),
    } as Record<string, string | Uint8Array>,
    caseJson,
    centerlines,
  };
}
